go({ k: "finish", lane: 7, lap: 2, t: 34.0, edited: false }, 35000);
go({ k: "heat", stat: "O", lanes: [{ lane: 7, time: 34.5, rank: 4 }] }, 41000);
chk("officiel différent de la plaque et des poires : corrigé", s.heat.lanes[7].fin.t === 34.5);
process.exit(ok ? 0 : 1);
